def generate_chart_base64(hist_df):
    try:
        import io
        import base64
        import matplotlib
        matplotlib.use('Agg')
        import mplfinance as mpf

        if hist_df is None or hist_df.empty:
            return None

        buf = io.BytesIO()
        chart_df = hist_df.tail(30).copy()
        mav_tuple = (20,) if len(chart_df) >= 20 else ()
        mpf.plot(
            chart_df,
            type='candle',
            volume=True,
            mav=mav_tuple,
            savefig=dict(fname=buf, format='png', bbox_inches='tight'),
            style='charles'
        )
        buf.seek(0)
        return base64.b64encode(buf.read()).decode('utf-8')
    except Exception as e:
        print(f"[CHART GEN ERROR] Failed to generate Base64 candlestick plot: {e}")
        return None

