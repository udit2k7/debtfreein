def fetch_upstox_v2_quotes(upstox_token, instrument_keys):
    import requests
    headers = {
        "Accept": "application/json",
        "Authorization": f"Bearer {upstox_token}"
    }
    keys_str = ",".join(instrument_keys)
    url = f"https://api.upstox.com/v2/market-quote/quotes?instrument_key={keys_str}"
    try:
        resp = requests.get(url, headers=headers, timeout=10)
        if resp.status_code == 200:
            return resp.json().get("data", {})
        else:
            print(f"[UPSTOX V2 ERROR] Quotes API returned status {resp.status_code}: {resp.text}")
            return {}
    except Exception as e:
        print(f"[UPSTOX V2 ERROR] Failed fetching quotes: {e}")
        return {}

def fetch_upstox_v2_candles(upstox_token, instrument_key, interval="15minute", days=5):
    import requests
    import datetime
    import pandas as pd

    today_str = datetime.date.today().strftime("%Y-%m-%d")
    from_date_str = (datetime.date.today() - datetime.timedelta(days=days)).strftime("%Y-%m-%d")
    url = f"https://api.upstox.com/v2/historical-candle/{instrument_key}/{interval}/{today_str}/{from_date_str}"
    headers = {
        "Accept": "application/json",
        "Authorization": f"Bearer {upstox_token}"
    }
    try:
        resp = requests.get(url, headers=headers, timeout=10)
        if resp.status_code == 200:
            candles = resp.json().get("data", {}).get("candles", [])
            if candles:
                df = pd.DataFrame(candles, columns=['Timestamp', 'Open', 'High', 'Low', 'Close', 'Volume', 'OI'])
                df = df.iloc[::-1].reset_index(drop=True)
                for col in ['Open', 'High', 'Low', 'Close', 'Volume']:
                    df[col] = pd.to_numeric(df[col], errors='coerce')
                return df
    except Exception as e:
        print(f"[UPSTOX V2 CANDLE ERROR] Failed to fetch candles for {instrument_key}: {e}")
    return None

def place_upstox_v2_order(upstox_token, instrument_key, transaction_type, quantity, product="I", order_type="MARKET", price=0.0):
    import requests
    headers = {
        "Accept": "application/json",
        "Content-Type": "application/json",
        "Authorization": f"Bearer {upstox_token}"
    }
    payload = {
        "quantity": int(quantity),
        "product": product, # "I" for Intraday
        "validity": "DAY",
        "price": float(price),
        "tag": "DEBTFREEIN_QUANT_BOT",
        "instrument_token": instrument_key,
        "order_type": order_type, # "MARKET", "LIMIT"
        "transaction_type": transaction_type, # "BUY", "SELL"
        "disclosed_quantity": 0,
        "trigger_price": 0.0,
        "is_amo": False
    }
    url = "https://api.upstox.com/v2/order/place"
    try:
        resp = requests.post(url, headers=headers, json=payload, timeout=10)
        print(f"[UPSTOX LIVE ORDER] {transaction_type} {quantity} shares of {instrument_key} | HTTP {resp.status_code}: {resp.text}")
        if resp.status_code in [200, 201]:
            return resp.json()
        else:
            return {"status": "error", "message": resp.text}
    except Exception as e:
        print(f"[UPSTOX LIVE ORDER ERROR] Exception placing order: {e}")
        return {"status": "error", "message": str(e)}

def manage_open_positions(db, upstox_token=None, is_live_trading_active=False):
    if not db:
        return

    collection_name = "live_trades_ledger" if is_live_trading_active else "paper_trades"
    print(f"[LIFECYCLE] Scanning open positions in '{collection_name}' (Live Mode: {is_live_trading_active})...")

    try:
        docs = db.collection(collection_name).stream()
        open_docs = []
        for doc in docs:
            d = doc.to_dict()
            status = d.get("status", "OPEN")
            if status == "OPEN":
                open_docs.append((doc.id, d))

        if not open_docs and is_live_trading_active:
            paper_docs = db.collection("paper_trades").stream()
            for doc in paper_docs:
                d = doc.to_dict()
                if d.get("status", "OPEN") == "OPEN":
                    open_docs.append((doc.id, d))
            if open_docs:
                collection_name = "paper_trades"

        if not open_docs:
            print("[LIFECYCLE] No active open positions found in Firestore.")
            return

        print(f"[LIFECYCLE] Found {len(open_docs)} open positions in '{collection_name}' to evaluate.")

        for doc_id, d in open_docs:
            symbol = d.get("symbol")
            entry_price = float(d.get("entry_price", 0) or 0)
            target_price = float(d.get("target_price", 0) or 0)
            stop_loss = float(d.get("stop_loss", 0) or 0)
            quantity = int(d.get("quantity", 100))

            if not symbol or entry_price <= 0:
                continue

            ltp = None
            clean_sym = symbol.replace(".NS", "")
            inst_key = d.get("instrument_key") or UPSTOX_INSTRUMENT_MAP.get(clean_sym)

            if upstox_token and inst_key:
                quotes_dict = fetch_upstox_v2_quotes(upstox_token, [inst_key])
                q_data = quotes_dict.get(inst_key) or (list(quotes_dict.values())[0] if quotes_dict else None)
                if q_data:
                    ltp = round(float(q_data.get("last_price") or q_data.get("ohlc", {}).get("close", 0)), 2)

            if not ltp or ltp <= 0:
                import yfinance as yf
                ticker_data = yf.Ticker(symbol)
                hist = ticker_data.history(period="1d", interval="1m")
                if not hist.empty:
                    ltp = round(float(hist["Close"].iloc[-1]), 2)

            if not ltp or ltp <= 0:
                continue

            pnl_pct = round(((ltp - entry_price) / entry_price) * 100.0, 2)

            print(f"[POSITION EVAL] {symbol} | Entry: ₹{entry_price} | LTP: ₹{ltp} | PnL: {pnl_pct}% | Target: ₹{target_price} | SL: ₹{stop_loss}")

            # 1. Trailing Stop-Loss Rule (Strike Protection)
            if pnl_pct >= 1.0 and stop_loss < entry_price:
                print(f"[STRIKE_PROTECTION_ACTIVATED] Symbol: {symbol} | PnL: +{pnl_pct}% | Moving SL from ₹{stop_loss} to breakeven ₹{entry_price}")
                stop_loss = entry_price
                db.collection(collection_name).document(doc_id).update({
                    "stop_loss": entry_price,
                    "trailing_stop_active": True,
                    "protection_log": "STRIKE_PROTECTION_ACTIVATED"
                })

            # 2. Take Profit Hit
            if target_price > 0 and ltp >= target_price:
                realized_pnl = round((target_price - entry_price) * quantity, 2)
                exit_time = datetime.datetime.utcnow().isoformat()

                upstox_exit_res = None
                if is_live_trading_active and upstox_token and inst_key:
                    upstox_exit_res = place_upstox_v2_order(upstox_token, inst_key, "SELL", quantity, product="I", order_type="MARKET")

                db.collection(collection_name).document(doc_id).update({
                    "status": "CLOSED_TP",
                    "exit_price": ltp,
                    "realized_pnl": realized_pnl,
                    "exit_timestamp": exit_time,
                    "exit_reason": f"Take Profit trigger hit: LTP ₹{ltp} >= Target ₹{target_price}",
                    "upstox_exit_order_response": upstox_exit_res
                })
                print(f"[AUTO-EXIT TP] Closed position for {symbol} at ₹{ltp} (Target: ₹{target_price}) | Realized PnL: +₹{realized_pnl}")
                continue

            # 3. Stop Loss Hit
            if stop_loss > 0 and ltp <= stop_loss:
                realized_pnl = round((stop_loss - entry_price) * quantity, 2)
                exit_time = datetime.datetime.utcnow().isoformat()

                upstox_exit_res = None
                if is_live_trading_active and upstox_token and inst_key:
                    upstox_exit_res = place_upstox_v2_order(upstox_token, inst_key, "SELL", quantity, product="I", order_type="MARKET")

                db.collection(collection_name).document(doc_id).update({
                    "status": "CLOSED_SL",
                    "exit_price": ltp,
                    "realized_pnl": realized_pnl,
                    "exit_timestamp": exit_time,
                    "exit_reason": f"Stop Loss trigger hit: LTP ₹{ltp} <= SL ₹{stop_loss}",
                    "upstox_exit_order_response": upstox_exit_res
                })
                print(f"[AUTO-EXIT SL] Closed position for {symbol} at ₹{ltp} (SL: ₹{stop_loss}) | Realized PnL: ₹{realized_pnl}")
                continue

    except Exception as e:
        print(f"[WARN] Error managing open positions: {e}")

def compute_technical_indicators(df):
    try:
        if df is None or len(df) < 20:
            return None

        import pandas_ta as ta

        ltp = round(float(df['Close'].iloc[-1]), 2)
        total_vol = int(df['Volume'].sum()) if 'Volume' in df else 0
        recent_vol = int(df['Volume'].iloc[-1]) if 'Volume' in df else 0

        # Calculate VWAP
        typical_price = (df['High'] + df['Low'] + df['Close']) / 3.0
        cum_tp_vol = (typical_price * df['Volume']).sum()
        cum_vol = df['Volume'].sum()
        vwap = round(float(cum_tp_vol / cum_vol), 2) if cum_vol > 0 else ltp

        # Calculate RSI (14) using pandas_ta or diff
        rsi_series = df.ta.rsi(length=14) if hasattr(df, 'ta') else None
        if rsi_series is not None and not rsi_series.empty and not str(rsi_series.iloc[-1]) == 'nan':
            rsi = round(float(rsi_series.iloc[-1]), 2)
        else:
            delta = df['Close'].diff()
            gain = delta.clip(lower=0)
            loss = -1 * delta.clip(upper=0)
            avg_gain = gain.rolling(window=14, min_periods=14).mean().iloc[-1]
            avg_loss = loss.rolling(window=14, min_periods=14).mean().iloc[-1]
            if avg_loss == 0 or avg_loss is None or str(avg_loss) == 'nan':
                rsi = 100.0
            else:
                rs = avg_gain / avg_loss
                rsi = round(float(100.0 - (100.0 / (1.0 + rs))), 2)

        # Calculate Moving Averages (20 & 50) and Average Volume
        sma_20 = round(float(df['Close'].rolling(window=min(20, len(df))).mean().iloc[-1]), 2)
        sma_50 = round(float(df['Close'].rolling(window=min(50, len(df))).mean().iloc[-1]), 2)
        vol_sma_20 = int(df['Volume'].rolling(window=min(20, len(df))).mean().iloc[-1]) if 'Volume' in df else total_vol

        vwap_relation = "ABOVE_VWAP" if ltp > vwap else "BELOW_VWAP"
        vwap_diff_pct = round(float(((ltp - vwap) / vwap) * 100.0), 2)

        # Swing High & Swing Low (20-period lookback) for Pivot Support & Resistance
        swing_high = round(float(df['High'].iloc[-20:].max()), 2)
        swing_low = round(float(df['Low'].iloc[-20:].min()), 2)
        support_zone = swing_low
        resistance_zone = swing_high

        # Fibonacci Retracement Levels (0.382, 0.500, 0.618)
        diff = swing_high - swing_low
        fib_382 = round(swing_high - 0.382 * diff, 2)
        fib_500 = round(swing_high - 0.500 * diff, 2)
        fib_618 = round(swing_high - 0.618 * diff, 2)

        # Candlestick Pattern Triggers (Bullish Engulfing & Doji)
        c_curr = float(df['Close'].iloc[-1])
        o_curr = float(df['Open'].iloc[-1])
        h_curr = float(df['High'].iloc[-1])
        l_curr = float(df['Low'].iloc[-1])
        c_prev = float(df['Close'].iloc[-2]) if len(df) >= 2 else c_curr
        o_prev = float(df['Open'].iloc[-2]) if len(df) >= 2 else o_curr

        is_bullish_engulfing = (c_prev < o_prev) and (c_curr > o_curr) and (c_curr >= o_prev) and (o_curr <= c_prev)
        is_doji = abs(c_curr - o_curr) <= 0.1 * (h_curr - l_curr) if (h_curr - l_curr) > 0 else False

        candlestick_trigger = "NONE"
        if is_bullish_engulfing:
            candlestick_trigger = "BULLISH_ENGULFING"
        elif is_doji:
            candlestick_trigger = "DOJI"

        volume_surge = recent_vol > (1.5 * vol_sma_20)

        return {
            "ltp": ltp,
            "total_volume": total_vol,
            "recent_volume": recent_vol,
            "vol_sma_20": vol_sma_20,
            "volume_surge": volume_surge,
            "vwap": vwap,
            "vwap_relation": vwap_relation,
            "vwap_diff_pct": vwap_diff_pct,
            "rsi": rsi,
            "sma_20": sma_20,
            "sma_50": sma_50,
            "swing_high": swing_high,
            "swing_low": swing_low,
            "support_zone": support_zone,
            "resistance_zone": resistance_zone,
            "fib_levels": {
                "fib_382": fib_382,
                "fib_500": fib_500,
                "fib_618": fib_618
            },
            "candlestick_trigger": candlestick_trigger
        }
    except Exception as e:
        print(f"Error computing indicators: {e}")
        return None

